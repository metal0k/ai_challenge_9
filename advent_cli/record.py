@dataclass(slots=True)
class Step:
    title: str
    args: list[str] = field(default_factory=list)
    stdin_lines: list[str] = field(default_factory=list)
    expect_failure: bool = False
    env: dict[str, str] = field(default_factory=dict)
    # Что запускать: `python -m <module>`. Умолчание — общий CLI курса, так что
    # шаги дней 01-05 не меняются ни на символ.
    module: str = DEFAULT_MODULE
    # Разбор мифа про temperature=0 (день 04) не зовёт CLI повторно — он
    # комментирует колонку «различных», уже напечатанную предыдущим шагом, и
    # цифру офлайн-замера из SPEC. args пустой сигналит _play() не запускать
    # subprocess, а просто показать текст: пустого args не бывает ни у одного
    # шага дней 01-03, так что это не меняет их поведение.
    note: str | None = None
    # Гигантский ввод дня 08: строка на ~265k токенов не живёт в сценарии —
    # читается из файла (его пишет шаг-генератор make_biginput) и уходит
    # в stdin ПОСЛЕ всех stdin_lines одной строкой. Файл без переводов строк:
    # \n обрезал бы реплику REPL до первого же символа. Закрытие stdin за
    # этим — штатный выход: REPL встречает EOF, прощается и завершается с 0,
    # отдельный /exit после файла не нужен.
    stdin_file: str | None = None
    # Per-step override of STEP_TIMEOUT. Day 09's bench runs the same dialog
    # twice — two dozen calls in one process — and dying at 180 s would kill
    # the take, not the harness. None keeps the shared limit for every other
    # step, so days 01-08 are untouched.
    timeout: int | None = None
    # Per-step override of STEP_PAUSE — how long the screen holds after each
    # REPL line. Measured on the w02d09 take: the answer naming the codeword
    # stayed readable for ~0.4 s, because the next line (/tokens) prints twenty
    # lines and scrolls it off. The day's headline needs a longer hold; None
    # keeps the shared pause, so earlier days are untouched.
    line_pause: float | None = None


def demo_steps(week: int, day: int, *, live: bool = False) -> list[Step]:
    """Сценарий демо для конкретного дня недели.

    Сценарии прошлых дней остаются в коде и выбираются по номеру —
    `advent record --day 1` обязана продолжать работать ровно как раньше.

    Незнакомая пара (неделя, день) — ошибка, а не «сойдёт день 01». Раньше
    здесь стоял безусловный fallback в _demo_steps_w01d01(week), и
    `record --week 2 --day 6` молча строил шаги `advent w02 chat` — команды,
    которой не существует: проверка, чей failure path продолжается, хуже
    отсутствующей проверки, потому что читается как пройденная (CLAUDE.md).
    """
    if week == 2 and day == 10:
        return _demo_steps_w02d10()
    if week == 2 and day == 9:
        return _demo_steps_w02d09()
    if week == 2 and day == 8:
        return _demo_steps_w02d08()
    if week == 2 and day == 7:
        return _demo_steps_w02d07()
    if week == 2 and day == 6:
        return _demo_steps_w02d06()
    if week == 3 and day == 11 and live:
        return _demo_steps_w03d11_live()
    if week == 3 and day == 11:
        return _demo_steps_w03d11()
    if week == 3 and day == 12:
        return _demo_steps_w03d12()
    if week == 1 and day == 5:
        return _demo_steps_w01d05()
    if week == 1 and day == 4:
        return _demo_steps_w01d04()
    if week == 1 and day == 3:
        return _demo_steps_w01d03()
    if week == 1 and day == 2:
        return _demo_steps_w01d02()
    if week == 1 and day == 1:
        return _demo_steps_w01d01(week)
    raise AdventError(
        f"Сценария демо для недели {week}, дня {day} нет.",
        hint="Добавь _demo_steps_wNNdDD() и ветку в demo_steps() — записывать нечего.",
    )


