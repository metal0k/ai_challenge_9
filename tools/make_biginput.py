"""Генератор гигантского ввода для демо серверного переполнения окна.

День 08 (SPEC-w02d08.md §5): одно сообщение длиннее окна модели — единственная
честная форма серверного переполнения, потому что клиентский override лимита
400 дать не может (PROBE-w02d08-overflow.md, факт 5). Скрипт пишет файл с
одной строкой на окно + margin токенов — её же подают в stdin агента.

Почему текст именно нумерованный набор РАЗНООБРАЗНЫХ фраз, а не повторяющаяся
строка: BPE сжимает монотонные повторы (PROBE, факт 4) — «а» × 700 000
схлопнулось бы в горсть токенов и переполнение не получилось бы в принципе.
Пул фраз взят с разной лексикой; номер в каждой фразе делает все строки
уникальными. Размер при этом считается ТОЧНЫМ счётчиком, а не прикидкой, —
поэтому плотность текста не критична: сборка сама дойдёт до цели.

Модуль демо, не часть агента: живёт в tools/, в агент не импортируется. Сеть
(скачивание tekken при холодном кэше и запрос карточки модели) допустима в
рантайме, но не в тестах — тесты гоняют build_text() с подставным счётчиком.
"""

