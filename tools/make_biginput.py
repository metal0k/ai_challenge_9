# Функция счёта: текст → токены. None — посчитать не удалось.
CountFn = Callable[[str], int | None]


def _phrase(n: int) -> str:
    """Фраза номер n. Индексы берутся от номера, а не от random: один и тот же
    n всегда даёт ту же фразу — сборка детерминирована и тестируема побайтово."""
    first = FRAGMENTS[n % len(FRAGMENTS)]
    second = FRAGMENTS[(n * 7 + 11) % len(FRAGMENTS)]
    third = FRAGMENTS[(n * 13 + 23) % len(FRAGMENTS)]
    return f"{n}) {first} {second} {third}"


def build_text(count: CountFn, target: int) -> str:
    """Собирает нумерованный текст не короче target токенов (по count).

    Итог — одна строка без единого перевода строки: файл подаётся в stdin REPL
    как одна реплика, и \n обрезал бы ввод до первой же фразы.

    Наращивание пропорционально недобору: измеренная плотность (токенов на
    фразу) используется, чтобы добрать сразу пачку фраз, а не по одной —
    пересчёт 262k токенов tekken'ом быстрый, но не бесплатный. Плотность растёт
    по ходу сборки (номера длиннеют, цифр больше), поэтому прикидка завышает
    пачку; запас 0.95 оставляет недобор, который добирается следующим проходом.
    Перелёт за итерацию тем самым сжимается геометрически.
    """
    if target <= 0:
        raise ValueError("target должен быть положительным")
    parts: list[str] = []
    measured = 0
    while True:
        if measured > 0:
            add = max(1, round((target - measured) * len(parts) / measured * 0.95))
        else:
            add = 16
        for _ in range(add):
            parts.append(_phrase(len(parts) + 1))
        text = " ".join(parts)
        measured = count(text)
        if measured is None:
            # Точный счётчик придирчив к форме (tokens.py), но одиночное
            # сообщение пользователя он считает всегда — до сюда дойти не
            # должны, и молча писать файл неизвестного размера нельзя.
            raise RuntimeError("счётчик не смог посчитать собранный текст")
        if measured >= target:
            return text


def window_for(model: str) -> int | None:
    """Размер окна модели из карточки /v1/models. None — карточки нет или
    окно в ней не заявлено: вызывающий решает, фатально это или нет."""
    config = Config.resolve(model=model)
    card = find_model(list_models(config), model)
    return tokens.context_limit(card)


def main(argv: list[str] | None = None) -> int:
    console.force_utf8()
    parser = argparse.ArgumentParser(
        description="Генератор гигантского ввода для демо переполнения окна модели."
    )
    parser.add_argument("--model", default=DEFAULT_MODEL, help="модель, окно которой превышаем")
    parser.add_argument(
        "--margin",
        type=int,
        default=DEFAULT_MARGIN,
        help="сколько токенов сверх окна добавить (по умолчанию 3000)",
    )
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="куда писать файл")
    args = parser.parse_args(argv)

    if args.margin <= 0:
        parser.error("--margin должен быть положительным: переполнение требует текста длиннее окна")

    try:
        limit = window_for(args.model)
    except ConfigError as exc:
        console.warn(str(exc))
        return 2
    except AdventError as exc:
        console.fail(exc)
        return exc.exit_code
    if limit is None:
        console.warn(
            f"у модели {args.model} в карточке нет размера окна — цель неизвестна, файл не пишется"
        )
        return 2

    # counter_for сам молчать не будет: скачка tekken при холодном кэше идёт
    # минуты и озвучивается через on_notice; оценочный счёт — с предупреждением.
    counter, warning = tokens.counter_for(args.model, on_notice=console.note)
    if warning:
        console.warn(warning)

    def count(text: str) -> int | None:
        return counter.count([{"role": "user", "content": text}])

    try:
        text = build_text(count, limit + args.margin)
    except RuntimeError as exc:
        console.warn(str(exc))
        return 1
    measured = count(text)
    assert measured is not None  # build_text уже считал этот же текст успешно

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")

    label = str(measured) if counter.exact else f"~{measured}"
    console.out.print(f"символов: {len(text)}  токенов: {label}  лимит окна: {limit}")
    # Это число — токены ГОЛОГО пользовательского сообщения (см. count() выше).
    # Агент отправит его вместе со своей системной персоной
    # (advent_core/prompts/default_system.md), и серверный 400 в шаге 4б
    # отчитается о промпте ЦЕЛИКОМ — число там будет чуть больше этого.
    # Пересчитывать здесь ту же форму, что уйдёт в запрос, — лишний прогон
    # точного счётчика ради пары десятков токенов персоны; проще и честнее
    # назвать расхождение вслух, чем гнаться за побайтовым совпадением двух
    # чисел, которые по смыслу считают разные вещи.
    console.note(
        "это токены одного пользовательского сообщения — агент добавит к ним "
        "ещё и системную персону, так что число в серверной ошибке 400 (шаг "
        "4б) будет чуть больше этого"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
